def get_key_value(data, key_name, case_sensitive=False):
    """
    Flexible dictionary value lookup with substring matching
    
    Args:
        data: Dictionary to search
        key_name: Substring to match in keys
        case_sensitive: Whether to match case
        
    Returns:
        Matched value or alarming errors
    """
    search_str = key_name if case_sensitive else key_name.lower()
    
    for key in data:
        key_str = key if case_sensitive else str(key).lower()
        if search_str in key_str:
            value_to_return = data[key]
            if len(value_to_return) == 0:
                return 'none'
            else:
                return value_to_return
    raise KeyError('not found '+key_name)

def get_estimate_var_clu(des):
    """
    Extracts cluster-level evaluation metrics
    
    Args:
        des: Description dictionary
        
    Returns:
        Tuple of (average metrics, inconsistency metrics)
    """
    estimate_avg_list = []
    estimate_incon_list = []
    
    # Define metrics to extract
    est_var = ["Voltage", "Temperature", "SOC"]
    estimate_sem1 = ['trend', 'transitions', 'fluctuation', 'outliers','mean','initial']
    estimate_sem2 = ['amplitude', 'fluctuation', 'mean']
    estimate_sem3 = ['trend', 'transition', 'fluctuation', 'outlier','mean','initial']
    
    for i in est_var:
        for j in estimate_sem1:
            if j == 'mean':
                jj = 'mean and std.'
            elif j == 'initial':
                jj = 'initial and final'
            else:
                jj = j
            des_per = get_key_value(des[i]['average'], j)
            estimate_avg_list.append([f"{jj}: "+des_per,i,jj,0])
            if j != 'fluctuation':
                des_per = get_key_value(des[i]['maximum'], j)
                estimate_avg_list.append([f"{jj}: "+des_per,i,jj,0])
                des_per = get_key_value(des[i]['minimum'], j)
                estimate_avg_list.append([f"{jj}: "+des_per,i,jj,0])
        for k in estimate_sem2:
            if k == 'mean':
                kk = 'mean and std.'
            else:
                kk = k
            des_per = get_key_value(des[i]['standard_deviation'], k)
            estimate_incon_list.append([f"{kk}: "+des_per, i, kk,0])
            des_per = get_key_value(des[i]['shannon_entropy'], k)
            estimate_incon_list.append([f"{kk}: "+des_per, i, kk,0])


    for l in estimate_sem3:
        target_keys = [key for key in des['Current'].keys() if l in key]
        if len(target_keys) == 1:
            if len(des['Current'][target_keys[0]]) == 0:
                estimate_avg_list.append([f"{target_keys[0]}: none.","current",target_keys[0],0])
            else:
                estimate_avg_list.append([f"{target_keys[0]}: "+des['Current'][target_keys[0]],"current",target_keys[0],0])
        else:
            print("no target found!!")
    return estimate_avg_list, estimate_incon_list


def get_estimate_list(pick_sample, has_glm=False):
    """Wrapper function to get both cluster and individual metrics"""
    
    json_list = pick_sample['descript c1']
    if type(json_list) == str:
        description_list1 = json.loads(json_list)
    else:
        description_list1 = (json_list)
  
    estimate_avg_list, estimate_incon_list = get_estimate_var_clu(description_list1)

    return estimate_avg_list, estimate_incon_list
    
def splice_result(result_list, response_list):
    """Combines evaluation results with original data"""
    
    results_all = []
    for i in range(len(response_list)):
        evaluate_list = response_list[i][0]
        estimate_list = response_list[i][1]
        result = result_list[i]
        for j in range(len(evaluate_list)):
            result_combine = [result[j]['score'],evaluate_list[j][0], estimate_list[j][0], evaluate_list[j][1],evaluate_list[j][2],evaluate_list[j][3],i]
            results_all.append(result_combine)
    return results_all

def pick_data(data, pers=0, sample=[]):
    """Filters and aggregates results by specified criteria"""
    
    if len(sample) != 0:
        data = [x for x in data if int(x[-1]/2) in sample]
    if pers != 0:
        data = [x for x in data if pers in x[1]]
    data_list = []
    for i in (sample):
        data_temp = [x[0] for x in data if int(x[-1]/2)==i]
        data_list.append(np.mean(data_temp))
    return data, data_list

def read_pickle_list(all_results):
    """Loads and transforms pickled results"""
    
    result_tran = [0] * len(all_results)
    for i in range(len(all_results)):
        result_read = all_results[i]
        idx = result_read[-1]
        result = result_read[0]
        result = result.replace("“",'"').replace("”",'"')
        response_result = json.loads(result)
        response_result = response_result["evaluate results"]
        result_tran[idx-1] = response_result

    return result_tran

