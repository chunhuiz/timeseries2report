def get_key_value(data, key_name, case_sensitive=False):
    """
    Flexible dictionary value lookup with substring matching
    
    Args:
        data: Dictionary to search
        key_name: Substring to match in keys
        case_sensitive: Whether to match case
        
    Returns:
        Matched value or alarming errors
    """
    search_str = key_name if case_sensitive else key_name.lower()
    
    for key in data:
        key_str = key if case_sensitive else str(key).lower()
        if search_str in key_str:
            value_to_return = data[key]
            if len(value_to_return) == 0:
                return 'none'
            else:
                return value_to_return
            
    raise KeyError('not found '+key_name)


def get_estimate_var_ind(des):
    """
    Extracts individual cell-level evaluation metrics
    
    Args:
        des: Description dictionary containing cell info
        
    Returns:
        Tuple of (shape metrics, statistical metrics)
    """
    # Handle different input formats
    if 'cells_info' in des:
        des_cell = des['cells_info']
    else:
        des_cell = des
        
    # Convert string to dict if needed    
    if type(des_cell) is str:
        des_cell = json.loads(des_cell)
        
    estimate_shape_list = []
    estimate_stat_list = []
    
    # Metrics to extract
    est_var = ["voltage", "temperature", "soc"]
    estimate_sem1 = ['trend', 'transition', 'fluctuation', 'outliers']
    estimate_sem2 = ['mean', 'initial']
    
    for i in range(len(des_cell)):
        for j in est_var:
            for k in estimate_sem1:
                if k == 'fluctuation':
                    if k not in des_cell[i][j]:
                        des_per = get_key_value(des_cell[i][j], 'flucutation')
                        estimate_shape_list.append([f"{k}: "+ des_per,j,k,1])
                    else:
                        des_per = get_key_value(des_cell[i][j], k)
                        estimate_shape_list.append([f"{k}: "+ des_per,j,k,1])
                else:
                    des_per = get_key_value(des_cell[i][j], k)
                    estimate_shape_list.append([f"{k}: "+ des_per,j,k,1])
                    
            for l in estimate_sem2:
                if l == 'mean':
                    ll = 'mean and std.'
                else:
                    ll = 'initial and final value'
                des_per = get_key_value(des_cell[i][j], l)
                estimate_stat_list.append([f"{ll}: "+ des_per,j,ll,1])
    return estimate_shape_list, estimate_stat_list


def get_estimate_list(pick_sample, has_glm=False):
    """
    Wrapper function to process all cell descriptions in a sample
    
    Handles 4 cell descriptions (c2-c5) per sample
    """    
    json_list2 = pick_sample['descript c2']
    json_list3 = pick_sample['descript c3']
    json_list4 = pick_sample['descript c4']
    json_list5 = pick_sample['descript c5']
    
    if type(json_list2) == str:
        description_list2 = json.loads(json_list2)
    else:
        description_list2 = (json_list2)
    
    if type(json_list3) == str:
        description_list3 = json.loads(json_list3)
    else:
        description_list3 = (json_list3)
    
    if type(json_list4) == str:
        description_list4 = json.loads(json_list4)
    else:
        description_list4 = (json_list4)
        
    if type(json_list5) == str:
        description_list5 = json.loads(json_list5)
    else:
        description_list5 = (json_list5)

    estimate_shape_list1, estimate_stat_list1 = get_estimate_var_ind(description_list2)
    estimate_shape_list2, estimate_stat_list2 = get_estimate_var_ind(description_list3)
    estimate_shape_list3, estimate_stat_list3 = get_estimate_var_ind(description_list4)
    estimate_shape_list4, estimate_stat_list4 = get_estimate_var_ind(description_list5)
    estimate_shape_list_up = estimate_shape_list1 + estimate_shape_list2
    estimate_shape_list_down = estimate_shape_list3 + estimate_shape_list4
    estimate_stat_list = estimate_stat_list1 + estimate_stat_list2 + estimate_stat_list3 + estimate_stat_list4
    return estimate_shape_list_up, estimate_shape_list_down, estimate_stat_list

    
def splice_result(result_list, response_list):
    """Combines evaluation results with original data for analysis"""
    results_all = []
    for i in range(len(response_list)):            
        evaluate_list = response_list[i][0]
        estimate_list = response_list[i][1]
        result = result_list[i]
        for j in range(len(evaluate_list)):
            result_combine = [result[j]['score'],evaluate_list[j][0], estimate_list[j][0], evaluate_list[j][1],evaluate_list[j][2],evaluate_list[j][3],i]
            results_all.append(result_combine)
    return results_all


def pick_data(data, pers=0, sample=[]):
    """Filters and aggregates results by specified criteria"""
    if len(sample) != 0:
        data = [x for x in data if int(x[-1]/3) in sample]
    if pers != 0:
        data = [x for x in data if pers in x[2]]
    data_list = []
    for i in (sample):
        data_temp = [x[0] for x in data if int(x[-1]/3)==i]
        data_list.append(np.mean(data_temp))
    return data, np.array(data_list)

def read_pickle_list(all_results):
    """Loads and transforms pickled results into evaluation format"""
    result_tran = [0] * len(all_results)
    
    for i in range(len(all_results)):
        # print(len(all_results))
        result_read = all_results[i]
        idx = result_read[-1]
        result = result_read[0]
        result = result.replace("“",'"').replace("”",'"')
        response_result = json.loads(result)
        response_result = response_result["evaluate results"]
        result_tran[idx-1] = response_result

    return result_tran


