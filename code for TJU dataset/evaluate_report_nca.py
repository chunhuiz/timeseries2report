def get_estimate_var_ind(des):
    if 'cells_info' in des:
        des_cell = des['cells_info']
    elif 'raw_response' in des:
        des_cell = des['raw_response']
    else:
        des_cell = des
    estimate_shape_list = []
    estimate_stat_list = []
    if "discharge capacity" in des_cell[0]:
        est_var = ["voltage", "charge capacity", "discharge capacity", "current"]
    elif "discharge_capacity" in des_cell[0]:
        est_var = ["voltage", "charge_capacity", "discharge_capacity", "current"]
    else:
        print('aaa')

    estimate_sem1 = ['trend', 'transition', 'fluctuation', 'outliers']
    estimate_sem2 = ['mean', 'initial']
    for i in range(len(des_cell)):
        for j in est_var:
            for k in estimate_sem1:
                if k == 'fluctuation':
                    if k not in des_cell[i][j]:
                        des_per = pr.get_key_value(des_cell[i][j], 'flucutation')
                        estimate_shape_list.append([f"{k}: "+ des_per,j,k,1])
                    else:
                        des_per = pr.get_key_value(des_cell[i][j], k)
                        estimate_shape_list.append([f"{k}: "+ des_per,j,k,1])
                else:
                    des_per = pr.get_key_value(des_cell[i][j], k)
                    estimate_shape_list.append([f"{k}: "+ des_per,j,k,1])
            for l in estimate_sem2:
                if l == 'mean':
                    ll = 'mean and std.'
                else:
                    ll = 'initial and final value'
                des_per = pr.get_key_value(des_cell[i][j], l)
                estimate_stat_list.append([f"{ll}: "+ des_per,j,ll,1])
    return estimate_shape_list, estimate_stat_list

def get_estimate_list(pick_sample, has_glm=False):
    json_list2 = pick_sample['descript c2']
    if isinstance(json_list2, str):
        description_list2 = json.loads(json_list2)
    else:
        description_list2 = (json_list2)

    estimate_shape_list, estimate_stat_list = get_estimate_var_ind(description_list2)

    return estimate_shape_list, estimate_stat_list
    
def splice_result(result_list, response_list):
    results_all = []
    for i in range(len(response_list)):
        evaluate_list = response_list[i][0]
        estimate_list = response_list[i][1]
        result = result_list[i]
        for j in range(len(evaluate_list)):
            result_combine = [result[j]['score'],evaluate_list[j][0], estimate_list[j][0], evaluate_list[j][1],evaluate_list[j][2],evaluate_list[j][3],i]
